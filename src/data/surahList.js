// بيبدأ من صفحة ١، وكل جزء بعده بيبدأ من 20×(رقمه−1)+2.
// تحقّق: الجزء ٣٠ = 20×29+2 = 582، ودي فعلًا أول صفحة في سورة النبأ
// حسب بيانات الصفحات فوق — فالمعادلة مظبوطة مش تخمين.
