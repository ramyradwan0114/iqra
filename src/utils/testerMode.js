/**
 * مواعيد التذكير — **من بكرة** لحد نهاية فترة الاختبار.
 *
 * بنبدأ من بكرة لأن اللي بيجدول دلوقتي هو التطبيق وهو مفتوح،
 * يعني المستخدم استعمله النهاردة خلاص ومحتاجش تذكير.
 *
 * بيرجّع [{ at, title, body, url }]
 */
export function testerSlots({ days = 14, now = new Date(), max = 45 } = {}) {
  const out = [];
  let i = 0;

  for (let d = 1; d <= days && out.length < max; d++) {
    for (const h of TESTER_HOURS) {
      if (out.length >= max) break;

      const at = new Date(now);
      at.setDate(at.getDate() + d);
      at.setHours(h, 0, 0, 0);

      if (at.getTime() <= now.getTime()) continue;
      if (at.getTime() >= TESTER_UNTIL.getTime()) continue;

      const p = TESTER_PROMPTS[i++ % TESTER_PROMPTS.length];
      out.push({ at, ...p });
    }
  }
  return out;
}
