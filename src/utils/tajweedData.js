// بيحوّل نص الـ API المُعلَّم لمقاطع { text, rule }
// مثال: "بِسْمِ <tajweed class=ham_wasl>ٱ</tajweed>للَّهِ"
export function parseTajweed(html) {
  if (!html) return [];
  const out = [];
  const re = /<tajweed class=([a-z_]+)>([\s\S]*?)<\/tajweed>|<span class=end>([\s\S]*?)<\/span>/g;
  let last = 0;
  let m;
  while ((m = re.exec(html)) !== null) {
    if (m.index > last) out.push({ text: html.slice(last, m.index), rule: null });
    if (m[1]) out.push({ text: m[2], rule: m[1] });
    else out.push({ text: m[3], rule: "end" });
    last = re.lastIndex;
  }
  if (last < html.length) out.push({ text: html.slice(last), rule: null });
  return out.filter((p) => p.text !== "");
}

// بيقسّم آية مُعلَّمة لكلمات، وكل كلمة مصفوفة مقاطع { text, rule }.
// ده اللي بيخلّي التلوين واللمس-وينطق يشتغلوا مع بعض: لو رجّعنا HTML خام
// كنا هنخسر حدود الكلمات اللي التوقيت مبني عليها.
export function tajweedWords(html) {
  const parts = parseTajweed(html).filter((p) => p.rule !== "end");
  const words = [];
  let cur = [];
  for (const p of parts) {
    const chunks = p.text.split(/(\s+)/);
    for (const c of chunks) {
      if (c === "") continue;
      if (/^\s+$/.test(c)) {
        if (cur.length) words.push(cur);
        cur = [];
      } else {
        cur.push({ text: c, rule: p.rule });
      }
    }
  }
  if (cur.length) words.push(cur);
  return words;
}

// الأحكام الموجودة فعليًا في آية — للمفتاح (legend)
export function rulesInVerse(html) {
  const set = new Set();
  for (const p of parseTajweed(html)) if (p.rule && TAJWEED_RULES[p.rule]) set.add(p.rule);
  return [...set];
}

